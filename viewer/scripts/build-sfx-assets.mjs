import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { validateSfxCatalogs } from '../../tools/validate-sfx-catalog.mjs';

const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
export const GENERATED_SFX_ROOT = path.join(repositoryRoot, 'viewer', 'generated', 'sfx');
export const GENERATED_SFX_MODULE = path.join(GENERATED_SFX_ROOT, 'catalog.mjs');

function compactRecipe(recipe) {
  const {
    id, family, duration_ms, attack_ms, release_ms, filter, delay, gain_trim,
    maximum_simultaneous_voices, interruption_group, sources,
  } = recipe;
  return {
    id, family, duration_ms, attack_ms, release_ms, filter, delay, gain_trim,
    maximum_simultaneous_voices, interruption_group, sources,
  };
}

function compactInteraction(interaction) {
  const {
    id, intent, inputs, priority, cooldown_ms, dedupe_group, overlap_policy, event_type,
    selector, recipe_id,
  } = interaction;
  return {
    id, intent, inputs, priority, cooldown_ms, dedupe_group, overlap_policy, event_type,
    selector, recipe_id,
  };
}

export async function expectedSfxModule() {
  await validateSfxCatalogs();
  const [recipeCatalog, uiCatalog] = await Promise.all([
    readFile(path.join(repositoryRoot, 'docs', 'audio', 'sfx-recipe-catalog.json'), 'utf8').then(JSON.parse),
    readFile(path.join(repositoryRoot, 'docs', 'audio', 'sfx-ui-catalog.json'), 'utf8').then(JSON.parse),
  ]);
  const recipes = recipeCatalog.recipes
    .filter((recipe) => recipe.status !== 'EXCLUDED')
    .map(compactRecipe);
  const interactions = uiCatalog.interactions.map(compactInteraction);
  const provenance = {
    recipe_schema_version: recipeCatalog.schema_version,
    interaction_schema_version: uiCatalog.schema_version,
    prototype_recipe_count: recipeCatalog.prototype_recipe_count,
    production_extension_count: recipeCatalog.production_extension_count,
  };
  return `// Generated by viewer/scripts/build-sfx-assets.mjs. Do not edit by hand.\n`
    + `export const SFX_CATALOG_PROVENANCE = Object.freeze(${JSON.stringify(provenance, null, 2)});\n`
    + `export const SFX_RUNTIME_POLICY = Object.freeze(${JSON.stringify(recipeCatalog.runtime_policy, null, 2)});\n`
    + `export const SFX_RECIPES = Object.freeze(${JSON.stringify(recipes, null, 2)});\n`
    + `export const SFX_INTERACTIONS = Object.freeze(${JSON.stringify(interactions, null, 2)});\n`;
}

export async function buildSfxAssets() {
  const source = await expectedSfxModule();
  await mkdir(GENERATED_SFX_ROOT, { recursive: true });
  await writeFile(GENERATED_SFX_MODULE, source, 'utf8');
  return { bytes: Buffer.byteLength(source), recipeCount: (source.match(/"duration_ms"/g) ?? []).length };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const result = await buildSfxAssets();
  console.log(`Built deterministic SFX runtime catalog: ${result.recipeCount} recipes, ${result.bytes} bytes.`);
}
